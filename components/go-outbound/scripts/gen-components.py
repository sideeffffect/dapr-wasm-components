#!/usr/bin/env python3
"""Generate internal/components: the Dapr components compiled into go-outbound.

daprd registers its components in github.com/dapr/dapr/cmd/daprd/components,
one file per component, selected by build tags (stablecomponents /
allcomponents). Some of them do not build for wasip1 (cgo-free SQLite via
modernc.org/libc, Pulsar, Dubbo, a few Azure SDKs), so go-outbound copies
the registration files of a curated set instead: daprd's stable set minus
what does not build for wasip1, plus a few allcomponents extras (crypto,
consul, redis lock, conversation). The build tag line is dropped. Re-run
after bumping github.com/dapr/dapr.
"""
import os, re, subprocess, sys

FILES = [
    # stable components that build for wasip1
    "bindings_aws_s3.go",
    "bindings_azure_cosmosdb.go",
    "bindings_azure_servicebusqueues.go",
    "bindings_azure_storagequeues.go",
    "bindings_cron.go",
    "bindings_http.go",
    "bindings_kafka.go",
    "bindings_localstorage.go",
    "bindings_postgres.go",
    "bindings_rabbitmq.go",
    "bindings_redis.go",
    "configuration_postgres.go",
    "configuration_redis.go",
    "middleware_http_bearer.go",
    "middleware_http_ratelimit.go",
    "middleware_http_uppercase.go",
    "nameresolution_kubernetes.go",
    "nameresolution_mdns.go",
    "pubsub_aws_snssqs.go",
    "pubsub_azure_servicebus_queues.go",
    "pubsub_azure_servicebus_topics.go",
    "pubsub_gcp_pubsub.go",
    "pubsub_in-memory.go",
    "pubsub_kafka.go",
    "pubsub_mqtt3.go",
    "pubsub_rabbitmq.go",
    "pubsub_redis.go",
    "secretstores_azure_keyvault.go",
    "secretstores_hashicorp_vault.go",
    "secretstores_kubernetes.go",
    "secretstores_local_env.go",
    "secretstores_local_file.go",
    "state_aws_dynamodb.go",
    "state_azure_cosmosdb.go",
    "state_azure_tablestorage.go",
    "state_cassandra.go",
    "state_cockroachdb.go",
    "state_gcp_firestore.go",
    "state_in-memory.go",
    "state_memcached.go",
    "state_mongodb.go",
    "state_mysql.go",
    "state_postgres.go",
    "state_redis.go",
    "state_sqlserver.go",
    # allcomponents extras
    "crypto_jwks.go",
    "crypto_localstorage.go",
    "lock_redis.go",
    "nameresolution_hashicorp_consul.go",
    "state_hashicorp_consul.go",
    "conversation_anthropic.go",
    "conversation_aws_bedrock.go",
    "conversation_deepseek.go",
    "conversation_echo.go",
    "conversation_googleai.go",
    "conversation_huggingface.go",
    "conversation_mistral.go",
    "conversation_ollama.go",
    "conversation_openai.go",
]

here = os.path.dirname(os.path.abspath(__file__))
root = os.path.join(here, "..")
dapr = subprocess.check_output(["go", "list", "-m", "-f", "{{.Dir}}", "github.com/dapr/dapr"], text=True, cwd=root).strip()
src = os.path.join(dapr, "cmd", "daprd", "components")
out = os.path.join(root, "internal", "components")
os.makedirs(out, exist_ok=True)
for f in os.listdir(out):
    if f.endswith(".go"):
        os.remove(os.path.join(out, f))
for name in FILES:
    text = open(os.path.join(src, name)).read()
    text, n = re.subn(r"\A//go:build [^\n]*\n\n", "", text)
    if n != 1:
        sys.exit(f"gen-components: {name}: no leading //go:build line")
    open(os.path.join(out, name), "w").write(
        "// Code generated by scripts/gen-components.py from github.com/dapr/dapr/cmd/daprd/components. DO NOT EDIT.\n\n" + text)
open(os.path.join(out, "doc.go"), "w").write(
    "// Package components registers the Dapr components compiled into go-outbound\n"
    "// (see scripts/gen-components.py for the selection).\npackage components\n")
